def _as_plain_object(value: Any) -> Any:
    if hasattr(value, "tolist"):
        return value.tolist()
    return value


def _is_research_dir_id(dir_id: Any) -> bool:
    return "research" in str(dir_id or "").lower()


def _to_text(value: Any) -> str:
    value = _as_plain_object(value)
    if isinstance(value, str):
        return value
    return json.dumps(value, ensure_ascii=False, indent=2)


def _coerce_text(value: Any) -> str:
    value = _as_plain_object(value)
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="replace")
    if isinstance(value, list):
        return "".join(_coerce_text(item) for item in value)
    if isinstance(value, dict):
        if "text" in value:
            return _coerce_text(value.get("text"))
        if "content" in value:
            return _coerce_text(value.get("content"))
    return str(value)


def _extract_judge_response_text(response: Any) -> str:
    response = _as_plain_object(response)
    if isinstance(response, (str, bytes)):
        return _coerce_text(response)

    if isinstance(response, dict):
        choices = response.get("choices")
        if isinstance(choices, list) and choices:
            first_choice = _as_plain_object(choices[0])
            if isinstance(first_choice, dict):
                message = _as_plain_object(first_choice.get("message"))
                if isinstance(message, dict):
                    return _coerce_text(message.get("content"))
        return _coerce_text(response.get("content"))

    choices = getattr(response, "choices", None)
    if choices:
        first_choice = choices[0]
        message = getattr(first_choice, "message", None)
        if message is not None:
            return _coerce_text(getattr(message, "content", None))

    return _coerce_text(getattr(response, "content", None))


