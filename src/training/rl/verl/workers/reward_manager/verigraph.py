def _parse_judge_result(text: str) -> tuple[float, str]:
    raw = str(text or "").strip()
    if not raw:
        return 0.0, "empty_response"
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError:
        return 0.0, "json_parse_error"
    raw_score = payload.get("score", 0.0)
    try:
        raw_score = float(raw_score)
    except Exception:
        raw_score = 0.0
    score = max(0.0, min(1.0, raw_score / 3.0))
    reason = str(payload.get("reasoning") or payload.get("reason") or "").strip()
    return score, reason

def _parse_infer_judge_result(text: str) -> tuple[float, str]:
    raw = str(text or "").strip()
    if not raw:
        return 0, "empty_response"
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError:
        return 0, "json_parse_error"

    raw_score = payload.get("score", 0)
    try:
        raw_score = float(raw_score)
    except Exception:
        raw_score = 0

    score = 1.0 if raw_score >= 0 else -1.0
    reason = str(payload.get("reasoning") or payload.get("reason") or "").strip()
    return score, reason


def _has_ground_truth(value: Any) -> bool:
    if value is None:
        return False
    if isinstance(value, str):
        return value.strip() != ""
    if isinstance(value, (list, tuple, set, dict)):
        return len(value) > 0
    return True

def _extract_infer_steps_from_trajectory(trajectory: Any) -> List[Dict[str, Any]]:
    trajectory = _as_plain_object(trajectory) or []
    if not isinstance(trajectory, list):
        return []

    text_parts = []
    for msg in trajectory:
        msg = _as_plain_object(msg)
        if not isinstance(msg, dict):
            continue
        if msg.get("role") == "assistant":
            content = _coerce_text(msg.get("content", ""))
            if "infer(" in content:
                text_parts.append(content)

    full_text = "\n\n".join(text_parts)
    if not full_text.strip():
        return []

    pattern = re.compile(
        r"""infer\s*\(\s*
            premises\s*=\s*\[(?P<premises>[^\]]*?)\]\s*,\s*
            conclusion\s*=\s*(?P<q1>["']{1,3})(?P<conclusion>.*?)(?P=q1)\s*,\s*
            reasoning\s*=\s*(?P<q2>["']{1,3})(?P<reasoning>.*?)(?P=q2)\s*
            \)""",
        re.DOTALL | re.VERBOSE,
    )

    infer_steps = []
    for m in pattern.finditer(full_text):
        premise_vars = [p.strip() for p in m.group("premises").split(",") if p.strip()]
        infer_steps.append(
            {
                "premise_vars": premise_vars,
                "conclusion": m.group("conclusion").strip(),
                "reasoning": m.group("reasoning").strip(),
            }
        )
    return infer_steps

def _build_claim_var_map(final_claims: List[str]) -> Dict[str, str]:
    return {f"c{i}": str(claim).strip() for i, claim in enumerate(final_claims, start=1)}

def _build_infer_judge_prompt(question: str, premise_texts: List[str], conclusion: str, reasoning: str) -> str:
    premises_text = "\n".join(f"- Premise {i+1}: {p}" for i, p in enumerate(premise_texts)) or "[EMPTY]"
    return (
        "Question:\n"
        f"{question.strip()}\n\n"
        "Premises:\n"
        f"{premises_text}\n\n"
        "Conclusion:\n"
        f"{conclusion.strip() or '[EMPTY]'}\n\n"
        "Reasoning:\n"
        f"{reasoning.strip() or '[EMPTY]'}"
    )


class _AsyncJudgeClient:
    def __init__(
        self,
        model_name: str,
        api_key: str,
        base_url: str,
        max_concurrency: int,
        timeout: int,
        temperature: float,
        max_tokens: int,
    ) -> None:
        from openai import AsyncOpenAI

        self.client = AsyncOpenAI(
            api_key=api_key,
            base_url=base_url,
            timeout=timeout,
        )
        self.model_name = model_name
        self.max_concurrency = max(1, int(max_concurrency))
        self.temperature = float(temperature)
        self.max_tokens = int(max_tokens)

